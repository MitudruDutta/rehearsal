def placeholder(name: str) -> str:
    return f"<{name.replace('-', '_')}>"


def describe_arguments(parser: argparse.ArgumentParser, path: str) -> tuple[str, list[tuple[str, str, str]]]:
    """A synopsis fragment and table rows (argument, default, meaning) for one parser, without its sub-commands."""
    formatter = parser._get_formatter()
    synopsis: list[str] = []
    rows: list[tuple[str, str, str]] = []
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._VersionAction, argparse._SubParsersAction)):
            continue
        if action.help == argparse.SUPPRESS:
            continue
        flag = action.option_strings[0] if action.option_strings else None
        name = flag or action.dest
        meaning = ARGUMENTS.get(f"{path} {name}") or ARGUMENTS.get(name) or ""  # our words first, then the command's own help
        if not meaning and action.help:
            meaning = tidy(formatter._expand_help(action))
            meaning = meaning[:1].upper() + meaning[1:]
        if not meaning:
            fail(f"the CLI argument '{path} {name}' has no help text; describe it in ARGUMENTS")
        if meaning and not meaning.endswith((".", "`", ")")):
            meaning += "."
        if action.choices:
            meaning += " One of: " + ", ".join(code(str(c)) for c in action.choices) + "."
        takes_value = action.nargs != 0
        if flag:
            value = f" {placeholder(action.dest)}" if takes_value else ""
            piece = f"{flag}{value}"
            repeat = "..." if isinstance(action, argparse._AppendAction) else ""
            synopsis.append(piece + repeat if action.required else f"[{piece}]{repeat}")
            default = action.default
            shown = "required" if action.required else ("" if default in (None, False, "", []) else code(str(default)))
            rows.append((code(piece), shown, meaning))
        else:
            piece = placeholder(action.dest)
            if action.nargs == "?":
                synopsis.append(f"[{piece}]")
                rows.append((code(piece), "", meaning))
            elif action.nargs == "+":
                synopsis.append(f"{piece}...")
                rows.append((code(piece), "required", meaning))
            else:
                synopsis.append(piece)
                rows.append((code(piece), "required", meaning))
    # positional arguments first, as a person types them
    synopsis.sort(key=lambda s: 0 if s.lstrip("[").startswith("<") else 1)
    rows.sort(key=lambda r: 0 if r[0].startswith("`<") else 1)
    return " ".join(synopsis), rows


def argument_table(rows: list[tuple[str, str, str]]) -> list[str]:
    if not rows:
        return []
    out = ["| Argument | Default | Meaning |", "|---|---|---|"]
    out += [f"| {a} | {d} | {m.replace('|', chr(92) + '|')} |" for a, d, m in rows]
    return out + [""]


def example_block(key: str) -> list[str]:
    out: list[str] = []
    for ex in EXAMPLES.get(key, []):
        out += ["```bash", ex["cmd"], "```", ""]
        if ex.get("out"):
            out += ["<Output>", "", "```text", ex["out"].rstrip("\n"), "```", "", "</Output>", ""]
        if ex.get("note"):
            out += [ex["note"], ""]
    return out


def cli_page() -> tuple[str, int]:
    parser = capture_parser()
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    commands: dict[str, argparse.ArgumentParser] = dict(sub.choices)

    groups: list[tuple[str, list[tuple[str, str]]]] = []
    for block in (parser.description or "").split("\n\n")[1:]:
        lines = block.splitlines()
        title = lines[0].rstrip(":")
        members = []
        for line in lines[1:]:
            name, _, summary = line.strip().partition(" ")
            members.append((name, summary.strip()))
        groups.append((title, members))
    grouped = [name for _, members in groups for name, _ in members]
    if sorted(grouped) != sorted(commands):
        fail("the groups in 'rehearsal --help' do not list every command")
    missing = [name for name in commands if name not in EXAMPLES]
    if missing:
        fail(f"cli_examples.json has no example for: {', '.join(sorted(missing))}")

    out = [
        "---",
        "title: CLI",
        f"description: Every rehearsal command, with its arguments and an example. The {len(commands)} commands, grouped by task.",
        "generated: true",
        "---",
        "",
        HEADER,
        "",
        "The `rehearsal` command does everything the console does, from a terminal or a script. It is part of the",
        "`rehearsal-kit` package. Commands print JSON, so you can pass the output to other tools.",
        "",
        "```bash",
        "pip install rehearsal-kit",
        "rehearsal login",
        "```",
        "",
        "Without an installation, run any command through `uvx`: `uvx --from rehearsal-kit rehearsal login`.",
        "",
        "The CLI uses the server and key that `rehearsal login` saved. The environment variables `REHEARSAL_URL` and",
        "`REHEARSAL_API_KEY` take precedence, which is what a CI job uses. When a command fails, the CLI prints the",
        "server's message and a hint: see [Errors](/reference/errors).",
        "",
        "## All commands",
        "",
    ]
    for title, members in groups:
        out += [f"**{title}**", "", "| Command | What it does |", "|---|---|"]
        for name, summary in members:
            out.append(f"| [`rehearsal {name}`](#rehearsal-{name}) | {esc(summary[:1].upper() + summary[1:])} |")
        out.append("")
    out += [
        "Two options work everywhere: `rehearsal --version` prints the installed version, and `--help` after any",
        "command prints its arguments.",
        "",
    ]

    for title, members in groups:
        out += [f"## {title}", ""]
        if title == "Run your own server":
            out += ["These commands run on the server, not against it. They need the server extra: `pip install 'rehearsal-kit[server]'`.", ""]
        for name, summary in members:
            cmd = commands[name]
            out += [f"### rehearsal {name}", ""]
            labels = []
            if name in COMING_SOON:
                labels.append('<Label kind="coming-soon" />')
            if name in SERVER_ONLY:
                labels.append('<Label kind="self-hosted" />')
            lead = esc(summary[:1].upper() + summary[1:]) + "."
            out += [(" ".join(labels) + " " if labels else "") + lead, ""]
            if name in NOTES:
                out += [NOTES[name], ""]
            if name in SPENDS:
                out += ['<Cost>', "", "This command spends model budget.", "", "</Cost>", ""]
            nested = next((a for a in cmd._actions if isinstance(a, argparse._SubParsersAction)), None)
            if nested is None:
                synopsis, rows = describe_arguments(cmd, name)
                out += ["```text", f"rehearsal {name} {synopsis}".rstrip(), "```", ""]
                out += argument_table(rows)
            else:
                helps = {a.dest: tidy(a.help or "") for a in nested._choices_actions}
                out += ["| Action | What it does |", "|---|---|"]
                blocks: list[str] = []
                for action_name, action_parser in nested.choices.items():
                    synopsis, rows = describe_arguments(action_parser, f"{name} {action_name}")
                    text = helps.get(action_name, "")
                    line = f"rehearsal {name} {action_name} {synopsis}".rstrip()
                    out.append(f"| {code(line)} | {esc(text[:1].upper() + text[1:])} |")
                    described = [r for r in rows if r[2]]
                    if any(r[0].startswith("`--") for r in described) or len(described) > 1:
                        blocks += [f"Arguments of `rehearsal {name} {action_name}`:", ""] + argument_table(rows)
                out.append("")
                out += blocks
            out += example_block(name)
    return "\n".join(out).rstrip("\n") + "\n", len(commands)


