def main() -> None:
    check = "--check" in sys.argv[1:]
    version = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]["version"]
    cli_text, cli_count = cli_page()
    parser = capture_parser()
    cli_commands = set(next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction)).choices)
    mcp_text, mcp_count = mcp_page(cli_commands)
    api_text, api_count = api_page()
    outputs = {
        DOCS / "content" / "reference" / "cli.mdx": cli_text,
        DOCS / "content" / "ai-assistants" / "mcp-tools.mdx": mcp_text,
        DOCS / "content" / "reference" / "plans-and-limits.mdx": plans_page(),
        DOCS / "content" / "reference" / "errors.mdx": errors_page(),
        DOCS / "content" / "reference" / "api.mdx": api_text,
        DOCS / "content" / "reference" / "python-sdk.mdx": sdk_page(),
        DOCS / "content" / "reference" / "configuration.mdx": config_page(),
        DOCS / "lib" / "generated" / "product.json": json.dumps({"version": version, "cliCommands": cli_count, "mcpTools": mcp_count, "apiOperations": api_count}, indent=2) + "\n",
    }
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        stale.append(path.relative_to(ROOT).as_posix())
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        sys.exit("These generated files differ from the code. Run docs/scripts/generate_reference.py and commit the result:\n  " + "\n  ".join(stale))
    print(("up to date: " if not stale else "written: ") + (", ".join(stale) if stale else f"{len(outputs)} files") + f" (rehearsal-kit {version}, {cli_count} commands, {mcp_count} tools)")


if __name__ == "__main__":
    main()
