def mcp_tools() -> tuple[str, list[dict[str, Any]]]:
    """Reads the tools from the source file itself, so the docs build needs no MCP package and starts no server."""
    tree = ast.parse((ROOT / "rehearsal" / "sdk" / "mcp.py").read_text(encoding="utf-8"))
    instructions = ""
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "INSTRUCTIONS" for t in node.targets):
            instructions = ast.literal_eval(node.value)
    build = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "build_server")
    tools = []
    for fn in build.body:
        if not isinstance(fn, ast.FunctionDef):
            continue
        if not any(isinstance(d, ast.Call) and ast.unparse(d.func) == "mcp.tool" for d in fn.decorator_list):
            continue
        args = fn.args.args
        defaults = [None] * (len(args) - len(fn.args.defaults)) + list(fn.args.defaults)
        params = []
        for arg, default in zip(args, defaults):
            annotation = ast.unparse(arg.annotation) if arg.annotation else "Any"
            optional = annotation.endswith(" | None")
            base = annotation.removesuffix(" | None")
            params.append({
                "name": arg.arg,
                "type": TYPES.get(base, base),
                "required": default is None,
                "default": None if default is None else ast.literal_eval(default),
                "nullable": optional,
            })
        tools.append({"name": fn.name, "doc": tidy(ast.get_docstring(fn) or ""), "params": params})
    return instructions, tools


def skill_costs() -> dict[str, tuple[str, str]]:
    """The cost table in the skill that assistants read: tool -> (typical cost, time)."""
    text = (ROOT / "rehearsal" / "assets" / "skill" / "SKILL.md").read_text(encoding="utf-8")
    section = text.split("## Money: ask before you spend", 1)[1].split("\nRules:", 1)[0]
    costs = {}
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 3 and cells[0].startswith("`"):
            costs[cells[0].strip("`")] = (cells[1], cells[2])
    return costs


