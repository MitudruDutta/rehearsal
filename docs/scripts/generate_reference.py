        f"Rehearsal({signature(sdk.Rehearsal.__init__)})",
        "```",
        "",
        "| Argument | Meaning |",
        "|---|---|",
        "| `api_key` | The key. Without it: the environment variable `REHEARSAL_API_KEY`, then the sign-in that `rehearsal login` saved |",
        f"| `base_url` | The server. Without it: `REHEARSAL_URL`, then the saved sign-in, then `{sdk.DEFAULT_URL}` |",
        "| `timeout` | Seconds to wait for one request |",
        "",
        "With no key anywhere, the constructor raises `ValueError`.",
        "",
        "### Errors",
        "",
        "A request that the server refuses raises `RehearsalError`. It has two fields: `status`, the HTTP status, and",
        "`detail`, the server's message. [Errors](/reference/errors) lists them.",
