def capture_parser() -> argparse.ArgumentParser:
    """The CLI builds its parser inside _main and parses at once. Stop it at that point and keep the parser."""
    import rehearsal.sdk.cli as cli

    class Captured(Exception):
        pass

    original = cli._Parser.parse_args

    def grab(self: argparse.ArgumentParser, *_: Any, **__: Any) -> Any:
        raise Captured(self)

    cli._Parser.parse_args = grab  # type: ignore[method-assign]
    try:
        cli._main([])
    except Captured as caught:
        return caught.args[0]
    finally:
        cli._Parser.parse_args = original  # type: ignore[method-assign]
    fail("the CLI did not build a parser")
    raise AssertionError


