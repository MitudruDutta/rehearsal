def schema_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return "object"
    if "anyOf" in schema:
        parts = [schema_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " or ".join(dict.fromkeys(parts))
    if "enum" in schema:
        return "one of " + ", ".join(code(str(v)) for v in schema["enum"])
    if schema.get("type") == "array":
        return "list of " + schema_type(schema.get("items", {})).replace("one of ", "")
    kind = {"integer": "integer", "number": "number", "string": "string", "boolean": "boolean", "object": "object"}.get(schema.get("type", ""), "any")
    low, high = schema.get("minimum"), schema.get("maximum")
    if low is not None and high is not None:
        kind += f", {low:g} to {high:g}"
    elif low is not None:
        kind += f", {low:g} or more"
    if "minLength" in schema and "maxLength" in schema:
        kind += f", {schema['minLength']} to {schema['maxLength']} characters"
    return kind


def access_of(method: str, path: str, needs_key: bool, endpoint: Any) -> str:
    """The least access an operation accepts, found by asking the server's own rule about a key of each scope. Some
    handlers add a check of their own as their first lines (p.require("admin")); those are read from the handler."""
    import inspect
    from types import SimpleNamespace

    from fastapi import HTTPException

    from rehearsal.api import auth

    if not needs_key:
        return "none"
    concrete = re.sub(r"\{[^}]+\}", "x", path)
    own = re.findall(r'^    p\.require\("(\w+)"\)', inspect.getsource(endpoint), flags=re.M)  # unconditional ones only

    def allowed(scopes: list[str]) -> bool:
        request = SimpleNamespace(url=SimpleNamespace(path=concrete), method=method, state=SimpleNamespace())
        try:
            principal = auth.authorize(request, auth.Principal(project_id="prj_x", key_id="key_x", scopes=scopes))  # type: ignore[arg-type]
            for scope in own:
                principal.require(scope)
            return True
        except HTTPException:
            return False

    if path.startswith("/v1/admin"):
        return "operator admin"
    if allowed([]):
        return "any key"
    if allowed(["read"]):
        level = "read"
    elif allowed(["evaluator"]):
        level = "evaluator"
    elif allowed(["write"]):
        level = "write"
    elif allowed(["write", "evaluator"]):
        level = "write and evaluator"
    elif allowed(["admin"]):
        level = "admin"
    else:
        fail(f"no scope is allowed to call {method} {path}")
    return level + (", or agent" if allowed(["agent"]) else "")


def body_table(name: str, schemas: dict[str, Any], heading: str) -> list[str]:
    schema = schemas[name]
    required = set(schema.get("required", []))
    meanings = API_FIELDS.get(name)
    out = [heading, "", "| Field | Type | Default | Meaning |" if meanings else "| Field | Type | Default |", "|---|---|---|---|" if meanings else "|---|---|---|"]
    nested: list[str] = []
    for field, spec in schema.get("properties", {}).items():
        if field in required:
            default = "required"
        elif spec.get("default") is None:
            default = "none"
        else:
            default = code(json.dumps(spec["default"]))
        row = f"| {code(field)} | {schema_type(spec)} | {default} |"
        if meanings is not None:
            if field not in meanings:
                fail(f"the API field '{name}.{field}' is not described in API_FIELDS")
            row += f" {meanings[field]} |"
        out.append(row)
        ref = spec.get("$ref", "").split("/")[-1]
        if ref and ref in schemas:
            nested += body_table(ref, schemas, f"Fields of `{field}`:")
    return out + [""] + nested


